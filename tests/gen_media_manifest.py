#!/usr/bin/env python3
"""Regenerate EX_MEDIA_FILES in index.html from exercise-media/ on disk.

Each self-hosted media id maps to [size0, hash0, size1, hash1, sizeLoop, hashLoop]
(bytes + first 8 hex chars of sha256; 0/'' when the file does not exist).
The offline-media download uses it to show exact sizes before downloading,
to verify every downloaded file byte-for-byte, and to version cache entries
(cache key = exercise-media/{id}/{file}?v={hash}). Gate 19 recomputes this
from disk and fails on any drift — run this script after changing any file in
exercise-media/.
"""
import hashlib, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MEDIA = os.path.join(ROOT, 'exercise-media')
FILES = ('0.jpg', '1.jpg', 'loop.mp4')
BEGIN = '// BEGIN EX_MEDIA_FILES (generated by tests/gen_media_manifest.py — do not edit by hand)'
END = '// END EX_MEDIA_FILES'


def manifest():
    out = {}
    for d in sorted(os.listdir(MEDIA)):
        p = os.path.join(MEDIA, d)
        if not os.path.isdir(p):
            continue
        row = []
        for f in FILES:
            fp = os.path.join(p, f)
            if os.path.isfile(fp):
                with open(fp, 'rb') as fh:
                    data = fh.read()
                row += [len(data), hashlib.sha256(data).hexdigest()[:8]]
            else:
                row += [0, '']
        if any(row[0::2]):
            out[d] = row
    return out


def render(m):
    lines = [BEGIN, 'const EX_MEDIA_FILES = {']
    for k, r in m.items():
        lines.append("  '%s':[%d,'%s',%d,'%s',%d,'%s']," % (k, *r))
    lines += ['};', END]
    return '\n'.join(lines)


def main():
    path = os.path.join(ROOT, 'index.html')
    src = open(path, encoding='utf-8').read()
    block = render(manifest())
    if BEGIN in src:
        new = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda _: block, src, count=1, flags=re.S)
    else:
        anchor = 'const EX_VIDEO_MAP = {'
        i = src.index(anchor)
        new = src[:i] + block + '\n' + src[i:]
    if new != src:
        open(path, 'w', encoding='utf-8').write(new)
        print('EX_MEDIA_FILES updated (%d ids)' % len(manifest()))
    else:
        print('EX_MEDIA_FILES already current')


if __name__ == '__main__':
    sys.exit(main())
